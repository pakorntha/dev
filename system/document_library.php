if (!function_exists('sis4_document_list')) {
    function sis4_document_list(): array
    {
        return array_values(sis4_document_catalog());
    }
}

if (!function_exists('sis4_document_get')) {
    function sis4_document_get(?string $documentId = null): array
    {
        $catalog = sis4_document_catalog();
        if ($documentId !== null && isset($catalog[$documentId])) {
            return $catalog[$documentId];
        }

        return reset($catalog) ?: [];
    }
